-- templates in Bangla and English, each declaring the only parameters it may carry (FR-NTF-08)
CREATE TABLE notify.templates (
  code            varchar(60) NOT NULL CHECK (code ~ '^[a-z_]+\.[a-z_]+$'),
  version         smallint NOT NULL CHECK (version >= 1),
  category        notify.category NOT NULL,
  channels        notify.channel[] NOT NULL DEFAULT '{}',
  allowed_params  text[] NOT NULL DEFAULT '{}',
  title_en        varchar(120) NOT NULL,
  title_bn        varchar(160) NOT NULL,
  body_en         varchar(1000) NOT NULL,
  body_bn         varchar(1500) NOT NULL,
  active          boolean NOT NULL DEFAULT true,
  PRIMARY KEY (code, version),
  -- FR-NTF-05: SMS only for security notices (OTPs bypass this table entirely)
  CONSTRAINT sms_only_for_security CHECK (NOT ('sms' = ANY (channels)) OR category = 'security'),
  -- FR-NTF-06: security notices go by SMS and e-mail
  CONSTRAINT security_by_sms_and_email CHECK (category <> 'security' OR (channels @> ARRAY['sms', 'email']::notify.channel[]))
);
CREATE UNIQUE INDEX templates_one_active ON notify.templates (code) WHERE active;

CREATE TABLE notify.preferences (
  user_id             uuid PRIMARY KEY REFERENCES identity.users(id),
  language            varchar(2) NOT NULL DEFAULT 'bn' CHECK (language IN ('bn', 'en')),
  email_transactional boolean NOT NULL DEFAULT true,     -- may be turned off; security notices ignore it

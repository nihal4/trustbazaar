  released_at  timestamptz,
  PRIMARY KEY (thread_id, case_type, case_id)
);
CREATE INDEX holds_live ON chat.thread_holds (thread_id) WHERE released_at IS NULL;

CREATE TABLE chat.staff_access_log (                                           -- SEC-LOG-01, append-only
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  staff_id   uuid NOT NULL REFERENCES identity.staff_accounts(id),
  thread_id  uuid NOT NULL REFERENCES chat.threads(id),
  case_type  chat.case_type NOT NULL,
  case_id    uuid NOT NULL,
  at         timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER staff_access_append_only BEFORE UPDATE OR DELETE ON chat.staff_access_log
  FOR EACH ROW EXECUTE FUNCTION identity.forbid_change();

-- detection terms (FR-CHT-07, FR-GAM-20), maintained by operators like Unit 3's screening terms
CREATE TABLE chat.detection_terms (
  id        integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  term      varchar(60) NOT NULL UNIQUE,      -- stored lower case, NFC
  flag      varchar(20) NOT NULL CHECK (flag IN ('payment_phrase', 'off_platform_app', 'credentials')),
  added_by  uuid REFERENCES identity.staff_accounts(id),
  added_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT term_normalised CHECK (term = lower(normalize(term, NFC)))
);

CREATE TABLE chat.outbox (                                                     -- DC-6
  id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  event_type      varchar(80) NOT NULL CHECK (event_type ~ '^chat\.[a-z_]+\.[a-z_]+$'),
  aggregate_id    uuid NOT NULL,
  payload         jsonb NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  attempts        smallint NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  dispatched_at   timestamptz
);
CREATE INDEX chat_outbox_pending ON chat.outbox (next_attempt_at) WHERE dispatched_at IS NULL;

-- ---------------------------------------------------------------- detection
-- Returns the warning flags for a text. Bangla digits are read as digits, separators between
-- digits are ignored, and Unicode is normalised (NFC). A flag never stops delivery (FR-CHT-07).
CREATE FUNCTION chat.normalise(p text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT lower(translate(normalize(p, NFC), '০১২৩৪৫৬৭৮৯', '0123456789'))
$$;

CREATE FUNCTION chat.detect(p_body text) RETURNS text[] LANGUAGE plpgsql STABLE AS $$
DECLARE
  t text; digits text; run text; f text[] := '{}';
BEGIN
  IF p_body IS NULL THEN RETURN f; END IF;
  t := chat.normalise(p_body);
  -- join digit groups split by spaces, dots, dashes or a leading +, then inspect each run
  digits := regexp_replace(t, '(?<=[0-9])[ .\-]+(?=[0-9])', '', 'g');
  FOR run IN SELECT m[1] FROM regexp_matches(digits, '([0-9]+)', 'g') AS m LOOP
    IF run ~ '^(880|88)?01[3-9][0-9]{8}$' THEN
      f := f || 'phone'::text;                       -- mobile and MFS wallet numbers
    ELSIF length(run) BETWEEN 10 AND 20 THEN
      f := f || 'account_number'::text;               -- bank accounts, card-like numbers
    END IF;
  END LOOP;
  IF t ~ '(https?://|www\.|\m(wa\.me|t\.me|bit\.ly)\M|\m[a-z0-9-]+\.(com|net|org|bd|me|io|xyz|link|shop|store|app)\M)' THEN
    f := f || 'link'::text;
  END IF;
  IF t ~ '[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}' THEN
    f := f || 'email'::text;
  END IF;
  -- Latin terms must stand as words ("imo" must not match "kimono"); Bangla terms match as
  -- substrings, because Bangla vowel signs are not word characters to the regex engine
  SELECT f || coalesce(array_agg(DISTINCT d.flag), '{}') INTO f
    FROM chat.detection_terms d
   WHERE CASE WHEN d.term ~ '^[ -~]+$'
              THEN t ~ ('(^|[^a-z0-9])' || regexp_replace(d.term, '([.^$*+?()\[\]{}|\\])', '\\\1', 'g')
                        || CASE WHEN d.term ~ '[a-z0-9]$' THEN '($|[^a-z0-9])' ELSE '' END)
              ELSE position(d.term IN t) > 0 END;
  RETURN ARRAY(SELECT DISTINCT x FROM unnest(f) x ORDER BY x);
END $$;

-- ---------------------------------------------------------------- operations
-- FR-CHT-01: open (or find) the thread; safe when two requests race
CREATE FUNCTION chat.open_thread(p_listing uuid, p_buyer uuid, p_seller uuid) RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE tid uuid;
BEGIN
  IF EXISTS (SELECT 1 FROM chat.blocks WHERE (blocker_id, blocked_id) IN ((p_buyer, p_seller), (p_seller, p_buyer))) THEN
    RAISE EXCEPTION 'messaging is blocked between these users' USING ERRCODE = 'insufficient_privilege';
  END IF;
  INSERT INTO chat.threads (listing_id, buyer_id, seller_id) VALUES (p_listing, p_buyer, p_seller)
  ON CONFLICT ON CONSTRAINT thread_one_per_buyer DO NOTHING RETURNING id INTO tid;
  IF tid IS NULL THEN
    SELECT id INTO tid FROM chat.threads WHERE listing_id = p_listing AND buyer_id = p_buyer;
  END IF;
  RETURN tid;
END $$;

-- FR-CHT-02, FR-CHT-07: post a message. Returns its sequence number; a resend with the same
-- client id returns the original message instead of a copy.
CREATE FUNCTION chat.post(p_thread uuid, p_sender uuid, p_client_id uuid, p_kind chat.message_kind,
                          p_body text, p_image_key varchar DEFAULT NULL)
RETURNS TABLE (message_id bigint, seq bigint, flags text[], duplicate boolean) LANGUAGE plpgsql AS $$
DECLARE th chat.threads; m chat.messages; other uuid;
BEGIN
  SELECT * INTO th FROM chat.threads WHERE id = p_thread FOR UPDATE;
  IF NOT FOUND OR p_sender NOT IN (th.buyer_id, th.seller_id) THEN
    RAISE EXCEPTION 'only the two participants can write in a thread' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO m FROM chat.messages WHERE thread_id = p_thread AND sender_id = p_sender AND client_msg_id = p_client_id;
  IF FOUND THEN
    RETURN QUERY SELECT m.id, m.seq, m.flags, true; RETURN;
  END IF;
  IF th.purged_at IS NOT NULL THEN RAISE EXCEPTION 'thread has been purged' USING ERRCODE = 'check_violation'; END IF;
  other := CASE WHEN p_sender = th.buyer_id THEN th.seller_id ELSE th.buyer_id END;
  IF EXISTS (SELECT 1 FROM chat.blocks WHERE (blocker_id, blocked_id) IN ((p_sender, other), (other, p_sender))) THEN
    RAISE EXCEPTION 'messaging is blocked between these users' USING ERRCODE = 'insufficient_privilege';
  END IF;
  INSERT INTO chat.messages (thread_id, seq, sender_id, client_msg_id, kind, body, image_key, flags)
  VALUES (p_thread, th.last_seq + 1, p_sender, p_client_id, p_kind, p_body, p_image_key, chat.detect(p_body))
  RETURNING * INTO m;
  UPDATE chat.threads SET last_seq = m.seq, last_message_at = m.created_at,
         buyer_delivered_seq  = CASE WHEN p_sender = buyer_id  THEN m.seq ELSE buyer_delivered_seq END,
         buyer_read_seq       = CASE WHEN p_sender = buyer_id  THEN m.seq ELSE buyer_read_seq END,
         seller_delivered_seq = CASE WHEN p_sender = seller_id THEN m.seq ELSE seller_delivered_seq END,
         seller_read_seq      = CASE WHEN p_sender = seller_id THEN m.seq ELSE seller_read_seq END
   WHERE id = p_thread;
  IF cardinality(m.flags) > 0 THEN
    INSERT INTO chat.outbox (event_type, aggregate_id, payload)
    VALUES ('chat.message.flagged', p_thread, jsonb_build_object('messageId', m.id, 'flags', m.flags, 'sender', p_sender));
  END IF;
  RETURN QUERY SELECT m.id, m.seq, m.flags, false;
END $$;

-- FR-CHT-05: the recipient's client reports what it has received and shown; values only move forward
CREATE FUNCTION chat.mark(p_thread uuid, p_user uuid, p_delivered bigint, p_read bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE th chat.threads; d bigint; r bigint;
BEGIN
  SELECT * INTO th FROM chat.threads WHERE id = p_thread FOR UPDATE;
  IF NOT FOUND OR p_user NOT IN (th.buyer_id, th.seller_id) THEN
    RAISE EXCEPTION 'only a participant can acknowledge messages' USING ERRCODE = 'insufficient_privilege';
  END IF;
  d := least(greatest(p_delivered, p_read), th.last_seq);
  r := least(p_read, th.last_seq);
  IF p_user = th.buyer_id THEN
    UPDATE chat.threads SET buyer_delivered_seq = greatest(buyer_delivered_seq, d),
                            buyer_read_seq = greatest(buyer_read_seq, r) WHERE id = p_thread;
  ELSE
    UPDATE chat.threads SET seller_delivered_seq = greatest(seller_delivered_seq, d),
                            seller_read_seq = greatest(seller_read_seq, r) WHERE id = p_thread;
  END IF;
END $$;

-- FR-CHT-10: an operator reads a thread only for a case that holds it; every read is logged
CREATE FUNCTION chat.staff_read(p_thread uuid, p_staff uuid, p_case_type chat.case_type, p_case uuid)
RETURNS SETOF chat.messages LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM chat.thread_holds WHERE thread_id = p_thread AND case_type = p_case_type
                   AND case_id = p_case AND released_at IS NULL) THEN
    RAISE EXCEPTION 'staff may read a thread only through an open case that concerns it' USING ERRCODE = 'insufficient_privilege';
  END IF;
  INSERT INTO chat.staff_access_log (staff_id, thread_id, case_type, case_id) VALUES (p_staff, p_thread, p_case_type, p_case);
  RETURN QUERY SELECT * FROM chat.messages WHERE thread_id = p_thread ORDER BY seq;
END $$;

-- retention (FR-CHT-04, SRS retention schedule): content of threads silent for p_after with no
-- live hold is removed. Returns the image keys whose files the service must delete.
CREATE FUNCTION chat.purge_due(p_after interval) RETURNS SETOF varchar LANGUAGE plpgsql AS $$
DECLARE th record;
BEGIN
  FOR th IN SELECT t.id FROM chat.threads t
             WHERE t.purged_at IS NULL AND t.last_message_at < now() - p_after
               AND NOT EXISTS (SELECT 1 FROM chat.thread_holds h WHERE h.thread_id = t.id AND h.released_at IS NULL)
             FOR UPDATE SKIP LOCKED LOOP
    RETURN QUERY SELECT m.image_key FROM chat.messages m WHERE m.thread_id = th.id AND m.image_key IS NOT NULL;
    UPDATE chat.messages SET body = NULL, image_key = NULL, purged_at = now() WHERE thread_id = th.id AND purged_at IS NULL;
    UPDATE chat.threads SET purged_at = now() WHERE id = th.id;
  END LOOP;
END $$;


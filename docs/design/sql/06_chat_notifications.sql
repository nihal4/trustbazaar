CREATE TYPE chat.message_kind AS ENUM ('text', 'image');
CREATE TYPE chat.case_type    AS ENUM ('dispute', 'report');

-- one thread per listing and prospective buyer, with the seller (FR-CHT-01)
CREATE TABLE chat.threads (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  listing_id            uuid NOT NULL REFERENCES listings.listings(id),
  buyer_id              uuid NOT NULL REFERENCES identity.users(id),
  seller_id             uuid NOT NULL REFERENCES identity.users(id),
  created_at            timestamptz NOT NULL DEFAULT now(),
  last_seq              bigint NOT NULL DEFAULT 0 CHECK (last_seq >= 0),
  last_message_at       timestamptz,
  -- per-participant watermarks: every message with seq <= the value is delivered / read (FR-CHT-05)
  buyer_delivered_seq   bigint NOT NULL DEFAULT 0,
  buyer_read_seq        bigint NOT NULL DEFAULT 0,
  seller_delivered_seq  bigint NOT NULL DEFAULT 0,
  seller_read_seq       bigint NOT NULL DEFAULT 0,
  purged_at             timestamptz,                    -- content removed at the end of retention
  CONSTRAINT thread_parties CHECK (buyer_id <> seller_id),
  CONSTRAINT thread_one_per_buyer UNIQUE (listing_id, buyer_id),
  CONSTRAINT watermarks_order CHECK (0 <= buyer_read_seq AND buyer_read_seq <= buyer_delivered_seq AND buyer_delivered_seq <= last_seq
                                 AND 0 <= seller_read_seq AND seller_read_seq <= seller_delivered_seq AND seller_delivered_seq <= last_seq)
);
CREATE INDEX threads_buyer  ON chat.threads (buyer_id, last_message_at DESC);
CREATE INDEX threads_seller ON chat.threads (seller_id, last_message_at DESC);
CREATE INDEX threads_retention ON chat.threads (last_message_at) WHERE purged_at IS NULL;

CREATE FUNCTION chat.thread_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.listing_id, NEW.buyer_id, NEW.seller_id, NEW.created_at) IS DISTINCT FROM (OLD.listing_id, OLD.buyer_id, OLD.seller_id, OLD.created_at) THEN
    RAISE EXCEPTION 'thread parties are fixed' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.last_seq < OLD.last_seq OR NEW.buyer_delivered_seq < OLD.buyer_delivered_seq OR NEW.buyer_read_seq < OLD.buyer_read_seq
     OR NEW.seller_delivered_seq < OLD.seller_delivered_seq OR NEW.seller_read_seq < OLD.seller_read_seq THEN
    RAISE EXCEPTION 'sequence and delivery watermarks only move forward' USING ERRCODE = 'check_violation';
  END IF;
  IF OLD.purged_at IS NOT NULL AND NEW.last_seq <> OLD.last_seq THEN
    RAISE EXCEPTION 'thread has been purged' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER thread_guard BEFORE UPDATE ON chat.threads FOR EACH ROW EXECUTE FUNCTION chat.thread_guard();

CREATE TABLE chat.messages (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  thread_id      uuid NOT NULL REFERENCES chat.threads(id),
  seq            bigint NOT NULL CHECK (seq >= 1),
  sender_id      uuid NOT NULL REFERENCES identity.users(id),
  client_msg_id  uuid NOT NULL,                        -- generated by the client; makes resending safe
  kind           chat.message_kind NOT NULL,
  body           varchar(2000),                        -- plain text only (FR-CHT-09)
  image_key      varchar(80),                          -- private chat_media volume; metadata stripped (FR-CHT-03)
  flags          text[] NOT NULL DEFAULT '{}',         -- warnings computed by chat.detect (FR-CHT-07, FR-GAM-20)
  created_at     timestamptz NOT NULL DEFAULT now(),
  purged_at      timestamptz,
  CONSTRAINT message_seq_unique UNIQUE (thread_id, seq),
  CONSTRAINT message_client_unique UNIQUE (thread_id, sender_id, client_msg_id),
  CONSTRAINT message_content CHECK (purged_at IS NOT NULL OR
         (kind = 'text'  AND body IS NOT NULL AND image_key IS NULL AND length(btrim(body)) >= 1) OR
         (kind = 'image' AND image_key IS NOT NULL AND (body IS NULL OR length(body) <= 300))),
  CONSTRAINT message_plain_text CHECK (body IS NULL OR body !~ '[\x01-\x08\x0B\x0C\x0E-\x1F\x7F]'),
  CONSTRAINT message_purged_empty CHECK (purged_at IS NULL OR (body IS NULL AND image_key IS NULL))
);
CREATE INDEX messages_thread ON chat.messages (thread_id, seq);

-- messages are never edited; at the end of retention only their content is removed
CREATE FUNCTION chat.message_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.purged_at IS NULL OR OLD.purged_at IS NOT NULL
     OR (NEW.thread_id, NEW.seq, NEW.sender_id, NEW.client_msg_id, NEW.kind, NEW.flags, NEW.created_at)
        IS DISTINCT FROM (OLD.thread_id, OLD.seq, OLD.sender_id, OLD.client_msg_id, OLD.kind, OLD.flags, OLD.created_at) THEN
    RAISE EXCEPTION 'chat messages cannot be edited' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER message_guard BEFORE UPDATE ON chat.messages FOR EACH ROW EXECUTE FUNCTION chat.message_guard();
CREATE TRIGGER message_no_delete BEFORE DELETE ON chat.messages FOR EACH ROW EXECUTE FUNCTION identity.forbid_change();

-- FR-CHT-08: a block stops messages in both directions until it is lifted
CREATE TABLE chat.blocks (
  blocker_id  uuid NOT NULL REFERENCES identity.users(id),
  blocked_id  uuid NOT NULL REFERENCES identity.users(id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (blocker_id, blocked_id),
  CONSTRAINT block_not_self CHECK (blocker_id <> blocked_id)
);
CREATE INDEX blocks_blocked ON chat.blocks (blocked_id);

-- holds: a dispute or report that concerns a thread keeps it beyond retention and is the only
-- ground on which staff may read it (FR-CHT-04, FR-CHT-10)
CREATE TABLE chat.thread_holds (

-- ---------------------------------------------------------------- safety of parameters (FR-NTF-08)
-- true if a text contains something no notification may carry: a phone number, an e-mail
-- address, an NID-like number, or a six-digit code
CREATE FUNCTION notify.unsafe(p text) RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
  SELECT x ~ '(^|[^0-9])(880|88)?01[3-9][0-9]{8}($|[^0-9])'
      OR x ~ '[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}'
      OR x ~ '(^|[^0-9])([0-9]{10}|[0-9]{13}|[0-9]{17})($|[^0-9])'
      OR x ~ '(^|[^0-9])[0-9]{6}($|[^0-9])'
  FROM (SELECT regexp_replace(chat.normalise(p), '(?<=[0-9])[ .\-]+(?=[0-9])', '', 'g') AS x) s
$$;
-- masks such content in user-written text (for example a listing title) before it is used
CREATE FUNCTION notify.mask(p text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT regexp_replace(regexp_replace(translate(normalize(p, NFC), '০১২৩৪৫৬৭৮৯', '0123456789'),
           '[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}', '[hidden]', 'gi'),
           '\+?[0-9]([ .\-]?[0-9]){5,}', '[hidden]', 'g')
$$;

CREATE FUNCTION notify.check_params() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE allowed text[]; k text; v jsonb;
BEGIN
  SELECT allowed_params INTO allowed FROM notify.templates WHERE code = NEW.template_code AND version = NEW.template_version;
  FOR k, v IN SELECT * FROM jsonb_each(NEW.params) LOOP
    IF NOT (k = ANY (allowed)) THEN
      RAISE EXCEPTION 'parameter % is not allowed in template %', k, NEW.template_code USING ERRCODE = 'check_violation';
    END IF;
    IF jsonb_typeof(v) NOT IN ('string', 'number', 'boolean') THEN
      RAISE EXCEPTION 'parameter % must be a plain value', k USING ERRCODE = 'check_violation';
    END IF;
    IF jsonb_typeof(v) = 'string' AND notify.unsafe(v #>> '{}') THEN
      RAISE EXCEPTION 'FR-NTF-08: parameter % contains contact details or a code', k USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;
  RETURN NEW;
END $$;
CREATE TRIGGER notification_params BEFORE INSERT OR UPDATE OF params ON notify.notifications
  FOR EACH ROW EXECUTE FUNCTION notify.check_params();

-- FR-NTF-03 to FR-NTF-06: create a notification and its e-mail and SMS deliveries. Returns NULL
-- if the same notification was already created (an event delivered twice).
CREATE FUNCTION notify.create(p_user uuid, p_code varchar, p_params jsonb, p_dedupe varchar)
RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE t notify.templates; nid uuid; email_ok boolean;
BEGIN
  SELECT * INTO t FROM notify.templates WHERE code = p_code AND active;
  IF NOT FOUND THEN RAISE EXCEPTION 'no active template %', p_code USING ERRCODE = 'check_violation'; END IF;
  INSERT INTO notify.notifications (user_id, template_code, template_version, params, dedupe_key)
  VALUES (p_user, t.code, t.version, coalesce(p_params, '{}'), p_dedupe)
  ON CONFLICT ON CONSTRAINT notification_once DO NOTHING RETURNING id INTO nid;
  IF nid IS NULL THEN RETURN NULL; END IF;
  SELECT coalesce((SELECT email_transactional FROM notify.preferences WHERE user_id = p_user), true) INTO email_ok;
  IF 'email' = ANY (t.channels) THEN
    INSERT INTO notify.deliveries (notification_id, channel, status)
    VALUES (nid, 'email', CASE WHEN t.category = 'security' OR email_ok THEN 'pending'::notify.delivery_status ELSE 'suppressed' END);
  END IF;
  IF 'sms' = ANY (t.channels) THEN
    INSERT INTO notify.deliveries (notification_id, channel) VALUES (nid, 'sms');
  END IF;
  RETURN nid;
END $$;

-- FR-NTF-07: schedule (or move) a reminder; a reminder already sent is re-armed only if the
-- deadline moved later (for example a takeover window restarted by a re-key)
CREATE FUNCTION notify.schedule_reminder(p_user uuid, p_kind notify.reminder_kind, p_subject uuid,
                                         p_due timestamptz, p_lead interval) RETURNS void LANGUAGE sql AS $$
  INSERT INTO notify.reminders (user_id, kind, subject_id, due_at, lead, fire_at) VALUES (p_user, p_kind, p_subject, p_due, p_lead, p_due - p_lead)
  ON CONFLICT ON CONSTRAINT reminder_once DO UPDATE
     SET due_at = EXCLUDED.due_at, fire_at = EXCLUDED.fire_at,
         status = CASE WHEN notify.reminders.status = 'scheduled' OR EXCLUDED.due_at > notify.reminders.due_at
                       THEN 'scheduled'::notify.reminder_status ELSE notify.reminders.status END,
         sent_at = CASE WHEN EXCLUDED.due_at > notify.reminders.due_at THEN NULL ELSE notify.reminders.sent_at END,
         cancelled_at = CASE WHEN EXCLUDED.due_at > notify.reminders.due_at THEN NULL ELSE notify.reminders.cancelled_at END
   WHERE notify.reminders.status <> 'cancelled' OR EXCLUDED.due_at > notify.reminders.due_at
$$;

-- the step happened: cancel the remaining reminders of that kind for the subject
CREATE FUNCTION notify.cancel_reminders(p_kind notify.reminder_kind, p_subject uuid) RETURNS integer LANGUAGE plpgsql AS $$
DECLARE n integer;
BEGIN
  UPDATE notify.reminders SET status = 'cancelled', cancelled_at = now()
   WHERE kind = p_kind AND subject_id = p_subject AND status = 'scheduled';
  GET DIAGNOSTICS n = ROW_COUNT; RETURN n;
END $$;

-- the reminder job claims due reminders once, even with several instances running
CREATE FUNCTION notify.claim_due_reminders(p_limit integer) RETURNS SETOF notify.reminders LANGUAGE sql AS $$
  -- a reminder whose deadline has already passed is never sent
  UPDATE notify.reminders SET status = 'cancelled', cancelled_at = now() WHERE status = 'scheduled' AND due_at <= now();
  UPDATE notify.reminders r SET status = 'sent', sent_at = now()
   WHERE r.id IN (SELECT id FROM notify.reminders WHERE status = 'scheduled' AND fire_at <= now() AND due_at > now()
                   ORDER BY fire_at LIMIT p_limit FOR UPDATE SKIP LOCKED)
  RETURNING r.*
$$;

-- DV-41: may a chat e-mail go to this user for this thread now? Records the send if so.
CREATE FUNCTION notify.chat_email_allowed(p_user uuid, p_thread uuid, p_window interval) RETURNS boolean LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO notify.chat_email_state (user_id, thread_id, last_sent_at) VALUES (p_user, p_thread, now())
  ON CONFLICT (user_id, thread_id) DO UPDATE SET last_sent_at = now()
   WHERE notify.chat_email_state.last_sent_at <= now() - p_window;
  RETURN FOUND;
END $$;


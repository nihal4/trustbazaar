);

CREATE TABLE notify.notifications (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id           uuid NOT NULL REFERENCES identity.users(id),
  template_code     varchar(60) NOT NULL,
  template_version  smallint NOT NULL,
  params            jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(params) = 'object'),
  dedupe_key        varchar(200) NOT NULL,              -- source event id + recipient + kind: consumers are idempotent
  subject_type      varchar(30) CHECK (subject_type ~ '^[a-z_]+$'), -- what it is about, so the client refreshes exactly that (I-55)
  subject_id        uuid,
  created_at        timestamptz NOT NULL DEFAULT now(),
  read_at           timestamptz,
  CONSTRAINT notification_subject CHECK ((subject_type IS NULL) = (subject_id IS NULL)),
  FOREIGN KEY (template_code, template_version) REFERENCES notify.templates(code, version),
  CONSTRAINT notification_once UNIQUE (user_id, dedupe_key)
);
CREATE INDEX notifications_user ON notify.notifications (user_id, created_at DESC);
CREATE INDEX notifications_unread ON notify.notifications (user_id) WHERE read_at IS NULL;

CREATE TABLE notify.deliveries (
  notification_id  uuid NOT NULL REFERENCES notify.notifications(id),
  channel          notify.channel NOT NULL,
  status           notify.delivery_status NOT NULL DEFAULT 'pending',
  attempts         smallint NOT NULL DEFAULT 0,
  next_attempt_at  timestamptz NOT NULL DEFAULT now(),
  provider_ref     varchar(100),
  last_error       varchar(60),                         -- an error code, never message content
  sent_at          timestamptz,
  PRIMARY KEY (notification_id, channel),
  CONSTRAINT delivery_sent_fields CHECK ((status = 'sent') = (sent_at IS NOT NULL))
);
CREATE INDEX deliveries_due ON notify.deliveries (next_attempt_at) WHERE status IN ('pending', 'failed');

